package de.craftplay.samsungtvbridge.data

object TvKeyMapping {
    fun generic(rawKey: String): String {
        val key = rawKey.trim().uppercase()
        return when (key) {
            "KEY_POWER", "KEY_POWERON", "KEY_POWEROFF", "POWER_ON", "POWER_OFF" -> "POWER"
            "KEY_HOME", "SMART_HOME", "SMART_HUB" -> "HOME"
            "KEY_RETURN", "KEY_BACK", "BACK" -> "BACK"
            "KEY_MENU" -> "MENU"
            "KEY_TOOLS", "TOOLS" -> "TOOLS"
            "KEY_SOURCE", "INPUT", "SOURCE" -> "SOURCE"
            "KEY_ENTER", "ENTER", "SELECT", "OK" -> "OK"
            "KEY_UP", "UP" -> "UP"
            "KEY_DOWN", "DOWN" -> "DOWN"
            "KEY_LEFT", "LEFT" -> "LEFT"
            "KEY_RIGHT", "RIGHT" -> "RIGHT"
            "KEY_VOLUP", "VOL_UP", "VOLUMEUP" -> "VOLUME_UP"
            "KEY_VOLDOWN", "VOL_DOWN", "VOLUMEDOWN" -> "VOLUME_DOWN"
            "KEY_MUTE" -> "MUTE"
            "KEY_CHUP", "CHANNELUP", "PROG_UP" -> "CHANNEL_UP"
            "KEY_CHDOWN", "CHANNELDOWN", "PROG_DOWN" -> "CHANNEL_DOWN"
            "KEY_GUIDE", "EPG" -> "GUIDE"
            "KEY_INFO" -> "INFO"
            "KEY_EXIT" -> "EXIT"
            "KEY_PLAY" -> "PLAY"
            "KEY_PAUSE" -> "PAUSE"
            "KEY_STOP" -> "STOP"
            "KEY_REWIND", "REWIND" -> "REWIND"
            "KEY_FF", "FAST_FORWARD", "FORWARD" -> "FAST_FORWARD"
            "KEY_REC", "RECORD" -> "RECORD"
            "KEY_RED", "RED" -> "RED"
            "KEY_GREEN", "GREEN" -> "GREEN"
            "KEY_YELLOW", "YELLOW" -> "YELLOW"
            "KEY_BLUE", "BLUE" -> "BLUE"
            "KEY_TTX_MIX", "KEY_TEXT", "TEXT", "TXT", "TELETEXT" -> "TELETEXT"
            "KEY_PRECH", "PRECH", "PREVIOUS_CHANNEL" -> "PREVIOUS_CHANNEL"
            "KEY_TV", "LIVE_TV", "TV" -> "TV"
            "KEY_0", "0", "DIGIT_0", "NUM0" -> "DIGIT_0"
            "KEY_1", "1", "DIGIT_1", "NUM1" -> "DIGIT_1"
            "KEY_2", "2", "DIGIT_2", "NUM2" -> "DIGIT_2"
            "KEY_3", "3", "DIGIT_3", "NUM3" -> "DIGIT_3"
            "KEY_4", "4", "DIGIT_4", "NUM4" -> "DIGIT_4"
            "KEY_5", "5", "DIGIT_5", "NUM5" -> "DIGIT_5"
            "KEY_6", "6", "DIGIT_6", "NUM6" -> "DIGIT_6"
            "KEY_7", "7", "DIGIT_7", "NUM7" -> "DIGIT_7"
            "KEY_8", "8", "DIGIT_8", "NUM8" -> "DIGIT_8"
            "KEY_9", "9", "DIGIT_9", "NUM9" -> "DIGIT_9"
            else -> key
        }
    }

    fun samsung(rawKey: String): String {
        val raw = rawKey.trim().uppercase()
        if (raw.startsWith("KEY_") && raw !in setOf("KEY_BACK")) return raw
        return when (generic(rawKey)) {
            "POWER" -> "KEY_POWER"
            "HOME" -> "KEY_HOME"
            "BACK" -> "KEY_RETURN"
            "MENU" -> "KEY_MENU"
            "TOOLS" -> "KEY_TOOLS"
            "SOURCE" -> "KEY_SOURCE"
            "OK" -> "KEY_ENTER"
            "UP" -> "KEY_UP"
            "DOWN" -> "KEY_DOWN"
            "LEFT" -> "KEY_LEFT"
            "RIGHT" -> "KEY_RIGHT"
            "VOLUME_UP" -> "KEY_VOLUP"
            "VOLUME_DOWN" -> "KEY_VOLDOWN"
            "MUTE" -> "KEY_MUTE"
            "CHANNEL_UP" -> "KEY_CHUP"
            "CHANNEL_DOWN" -> "KEY_CHDOWN"
            "GUIDE" -> "KEY_GUIDE"
            "INFO" -> "KEY_INFO"
            "EXIT" -> "KEY_EXIT"
            "PLAY" -> "KEY_PLAY"
            "PAUSE" -> "KEY_PAUSE"
            "STOP" -> "KEY_STOP"
            "REWIND" -> "KEY_REWIND"
            "FAST_FORWARD" -> "KEY_FF"
            "RECORD" -> "KEY_REC"
            "RED" -> "KEY_RED"
            "GREEN" -> "KEY_GREEN"
            "YELLOW" -> "KEY_YELLOW"
            "BLUE" -> "KEY_BLUE"
            "TELETEXT" -> "KEY_TTX_MIX"
            "PREVIOUS_CHANNEL" -> "KEY_PRECH"
            "TV" -> "KEY_TV"
            "DIGIT_0" -> "KEY_0"
            "DIGIT_1" -> "KEY_1"
            "DIGIT_2" -> "KEY_2"
            "DIGIT_3" -> "KEY_3"
            "DIGIT_4" -> "KEY_4"
            "DIGIT_5" -> "KEY_5"
            "DIGIT_6" -> "KEY_6"
            "DIGIT_7" -> "KEY_7"
            "DIGIT_8" -> "KEY_8"
            "DIGIT_9" -> "KEY_9"
            else -> throw IllegalStateException("Samsung-Key derzeit nicht unterstuetzt: $rawKey")
        }
    }

